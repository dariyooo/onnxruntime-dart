// Generates lib/src/bindings/config_keys.g.dart from the pinned headers.
//
// ONNX Runtime declares its configuration keys as `static const char* const`,
// which has internal linkage, so ffigen cannot emit them. They matter more than
// convenience: on the web there are no typed option setters at all, and config
// entries are the only way to set most options.
//
// Run alongside ffigen after moving the submodule.

import 'dart:io';

const _headers = {
  'SessionConfig': 'onnxruntime_session_options_config_keys.h',
  'RunConfig': 'onnxruntime_run_options_config_keys.h',
  'EnvConfig': 'onnxruntime_env_config_keys.h',
};

/// Stripped from a constant's name, longest first. ONNX Runtime uses several
/// prefixes in the same header, and a few keys carry none at all.
const _prefixes = [
  'kOrtSessionOptionsConfig',
  'kOrtSessionOptions',
  'kOrtSessionOption',
  'kOrtRunOptionsConfig',
  'kOrtRunOptions',
  'kOrtEpDynamicOptions',
  'kOrtEnv',
  'kOrt',
  'k',
];

void main() {
  final root = _repositoryRoot();
  final buffer = StringBuffer()
    ..writeln('// AUTO GENERATED FILE, DO NOT EDIT.')
    ..writeln('//')
    ..writeln('// Generated by tool/generate_config_keys.dart from the headers')
    ..writeln('// in third_party/onnxruntime. Regenerate after moving the')
    ..writeln('// submodule.')
    ..writeln()
    ..writeln('/// Configuration keys understood by ONNX Runtime.')
    ..writeln('///')
    ..writeln('/// Most options are set through these rather than through typed')
    ..writeln('/// calls, and on the web they are the only mechanism.')
    ..writeln('library;');

  var total = 0;
  for (final MapEntry(key: className, value: file) in _headers.entries) {
    final path =
        '$root/third_party/onnxruntime/include/onnxruntime/core/session/$file';
    final keys = _extract(File(path).readAsStringSync());
    if (keys.isEmpty) {
      stderr.writeln('no configuration keys found in $file');
      exit(1);
    }
    total += keys.length;

    buffer
      ..writeln()
      ..writeln('/// Keys from `$file`.')
      ..writeln('abstract final class $className {');
    for (final MapEntry(key: name, value: value) in keys.entries) {
      buffer.writeln("  static const $name = '$value';");
    }
    buffer
      ..writeln()
      ..writeln('  /// Every key in this group, for tests and diagnostics.')
      ..writeln('  static const all = <String>[')
      ..writeln(keys.keys.map((n) => '    $n,').join('\n'))
      ..writeln('  ];')
      ..writeln('}');
  }

  File('$root/packages/onnxruntime_dart/lib/src/bindings/config_keys.g.dart')
      .writeAsStringSync(buffer.toString());
  stdout.writeln('generated $total configuration keys');
}

/// Pulls every `static const char* const k... = "...";` out of a header.
///
/// Declarations wrap, so whitespace is matched loosely rather than assuming one
/// line.
Map<String, String> _extract(String header) {
  final pattern = RegExp(
    r'static\s+const\s+char\*\s+const\s+(k\w+)\s*=\s*"([^"]*)"\s*;',
  );
  final keys = <String, String>{};
  for (final match in pattern.allMatches(header)) {
    final name = _dartName(_strip(match.group(1)!));
    if (keys.containsKey(name)) {
      throw StateError('two keys map to $name, one would be lost');
    }
    keys[name] = match.group(2)!;
  }
  return keys;
}

String _strip(String name) {
  for (final prefix in _prefixes) {
    if (name.startsWith(prefix) && name.length > prefix.length) {
      return name.substring(prefix.length);
    }
  }
  return name;
}

/// `DisablePrepacking` to `disablePrepacking`, keeping runs of capitals intact
/// so `EnableORTFormatModel` does not become `enableORTFormatModel`.
String _dartName(String name) {
  final leading = RegExp(r'^[A-Z]+').firstMatch(name)!.group(0)!;
  return leading.length == 1
      ? name[0].toLowerCase() + name.substring(1)
      : leading.substring(0, leading.length - 1).toLowerCase() +
            name.substring(leading.length - 1);
}

String _repositoryRoot() {
  for (var dir = Directory.current;; dir = dir.parent) {
    if (Directory('${dir.path}/third_party/onnxruntime').existsSync()) {
      return dir.path;
    }
    if (dir.parent.path == dir.path) {
      throw StateError('no third_party/onnxruntime above ${Directory.current}');
    }
  }
}
